<?php
/**
 * includes/class-template-controller.php — Template Controller (batch 7)
 * ══════════════════════════════════════════════════════════════
 * Contract (architecture §7.5 and §18 row includes/class-template-controller.php):
 *   - Registers the template_include filter and returns the Runtime template
 *     only when the queried object matches the owned page ID or its pinned
 *     WPML translation.
 *   - No hijacking via the public slug, a query parameter, or
 *     is_page_template — matching is by ID only.
 *   - It does not create the page; idempotent page creation/linking is the
 *     Installer's responsibility (§7.2 item 9 and §7.5) via the option
 *     'hal_frontend_dashboard_page_id'.
 *   - Before returning it verifies realpath/readability and that the file
 *     stays inside HAL_FRONTEND_DASHBOARD_RUNTIME_DIR for this request (one
 *     release per request); on failure it never guesses a template nor
 *     builds a path from input, and returns the original template with a
 *     safe diagnostic logged (generic code in the log, no paths or data).
 *   - Fail-safe when the Runtime is not ready: a missing release context or
 *     file always returns the original template.
 *   - Runtime parts loader (render_part): a closed allowlist for the twelve
 *     dashboard parts, explicit args passing guarded by EXTR_SKIP, and the
 *     same containment check before every include. Parts perform no write
 *     operations and never bypass the registry/capabilities (§8.3) — the
 *     capability check lives inside each part and the B3-08 gates sit at
 *     the consumption points.
 *
 * Single shared source file (§6.1): this includes/ copy is the source of
 * truth; the Runtime copy at runtime/infrastructure/class-template-controller.php
 * (generated by the build from this file — §6.1). No business logic here, no
 * AJAX, no secrets; no state, no network.
 * class_exists guard after the 2026-09-17 audit (prevents a fatal if both copies ever load in one process — no path to that today)
 * ══════════════════════════════════════════════════════════════
 */

defined( 'ABSPATH' ) || exit;

if ( ! class_exists( 'HAL_Frontend_Dashboard_Template_Controller' ) ) {
	final class HAL_Frontend_Dashboard_Template_Controller {

		/**
		 * Option whose name is the approved contract (§7.5) — written by the
		 * Installer after verifying the WP_Post, its type and its status.
		 * Absence or a garbage row = no target page (safe failure).
		 */
		const PAGE_ID_OPTION = 'hal_frontend_dashboard_page_id';

		/** Relative shell template path inside the release root. */
		const TEMPLATE_RELATIVE = 'templates/dashboard.php';

		/**
		 * The twelve approved dashboard parts (§18/§19) — a closed allowlist;
		 * any other name is rejected fail-closed before any filesystem access.
		 */
		const PANEL_PARTS = array(
			'overview', 'posts', 'files', 'bookings', 'seo', 'translations',
			'profile', 'inbox', 'finance', 'store', 'admin', 'members',
		);

		/** Registers the template filter — invoked once when the file loads in the Runtime. */
		public static function register(): void {
			add_filter( 'template_include', array( self::class, 'resolve_template' ), 10, 1 );
		}

		/**
		 * The page ID owned by the Installer, or 0 when absent/invalid.
		 * Read verification identical to the Installer: a WP_Post of type page,
		 * published or private.
		 */
		public static function get_owned_page_id(): int {
			$page_id = absint( get_option( self::PAGE_ID_OPTION, 0 ) );
			if ( $page_id < 1 ) {
				return 0;
			}
			$post = get_post( $page_id );
			if ( ! $post instanceof WP_Post || 'page' !== $post->post_type
				|| ! in_array( $post->post_status, array( 'publish', 'private' ), true ) ) {
				return 0;
			}
			return $page_id;
		}

		/**
		 * Target page IDs: the owned page plus its WPML translations via the
		 * official filters (wpml_element_trid/wpml_get_element_translations
		 * with type post_page). Without WPML it returns [owned] only. Without
		 * an owned state it returns [].
		 *
		 * @return int[]
		 */
		public static function get_target_page_ids(): array {
			$owned = self::get_owned_page_id();
			if ( $owned < 1 ) {
				return array();
			}

			$ids = array( $owned );

			if ( defined( 'ICL_SITEPRESS_VERSION' ) && has_filter( 'wpml_element_trid' ) ) {
				$trid = apply_filters( 'wpml_element_trid', null, $owned, 'post_page' );
				$trid = is_numeric( $trid ) ? (int) $trid : 0;
				if ( $trid > 0 ) {
					static $cache = [];
					$blog = function_exists( 'get_current_blog_id' ) ? (int) get_current_blog_id() : 0;
					if ( array_key_exists( $blog, $cache ) ) {
						return $cache[ $blog ];
					}
					$translations = apply_filters( 'wpml_get_element_translations', null, $trid, 'post_page' );
					if ( is_array( $translations ) ) {
						foreach ( $translations as $translation ) {
							$translation_id = is_object( $translation ) && isset( $translation->element_id )
								? absint( $translation->element_id )
								: 0;
							if ( $translation_id > 0 && ! in_array( $translation_id, $ids, true ) ) {
								$ids[] = $translation_id;
							}
						}
					}
					$cache[ $blog ] = $ids;
				}
			}

			return $ids;
		}

		/** Is this ID a target page (owned or a pinned WPML translation)? */
		public static function is_target_page_id( int $page_id ): bool {
			return $page_id > 0 && in_array( $page_id, self::get_target_page_ids(), true );
		}

		/**
		 * The target predicate shared by all consumers (template_include +
		 * enqueues + body classes — §7.5: one and the same predicate). The
		 * queried object is of type page and its ID is within the target set;
		 * otherwise false. It reads no query parameter and no public slug.
		 */
		public static function is_target_query(): bool {
			$queried = get_queried_object();
			if ( ! $queried instanceof WP_Post || 'page' !== $queried->post_type ) {
				return false;
			}
			return self::is_target_page_id( (int) $queried->ID );
		}

		/**
		 * Callback for template_include: the Runtime template for the target
		 * page only, the original template in every other case (fail-safe).
		 *
		 * @param mixed $template The current WordPress template.
		 * @return mixed A verified Runtime template or the original template as-is.
		 */
		public static function resolve_template( $template ) {
			if ( ! is_string( $template ) || '' === $template ) {
				return $template;
			}
			if ( ! self::is_target_query() ) {
				return $template;
			}

			$path = self::validated_runtime_path( self::TEMPLATE_RELATIVE );
			if ( null === $path ) {
				self::log_safe( 'template_unavailable' );
				return $template;
			}

			return $path;
		}

		/**
		 * Runtime parts loader: includes an approved dashboard part inside the
		 * verified release path, with explicit args (EXTR_SKIP protects the
		 * local scope variables). An unapproved or missing part = fail-closed
		 * with no output.
		 *
		 * @param string               $part Part name from the allowlist.
		 * @param array<string,mixed>  $args Explicit named variables passed by the shell.
		 */
		public static function render_part( string $part, array $args = array() ): void {
			if ( ! preg_match( '/^[a-z0-9_-]{1,40}$/', $part ) || ! in_array( $part, self::PANEL_PARTS, true ) ) {
				self::log_safe( 'invalid_panel_part' );
				return;
			}

			$path = self::validated_runtime_path( 'templates/dashboard/' . $part . '.php' );
			if ( null === $path ) {
				self::log_safe( 'panel_part_unavailable' );
				return;
			}

			extract( $args, EXTR_SKIP ); // phpcs:ignore WordPress.PHP.DontExtract.extract_extract -- Parts contract: named keys from the shell only, and the EXTR_SKIP guard protects this function's variables.
			include $path;
		}

		/**
		 * Path verification inside the release for this request: a release
		 * context exists, realpath for root and path, readability possible,
		 * and the file stays inside the root. Any failure returns null (safe
		 * failure) — no path from input, no guessing.
		 */
		private static function validated_runtime_path( string $relative ): ?string {
			if ( ! defined( 'HAL_FRONTEND_DASHBOARD_RUNTIME_DIR' ) ) {
				return null;
			}
			$root = HAL_FRONTEND_DASHBOARD_RUNTIME_DIR;
			if ( ! is_string( $root ) || '' === $root ) {
				return null;
			}

			$real_root = realpath( $root );
			if ( false === $real_root ) {
				return null;
			}

			$candidate = $root . str_replace( '/', DIRECTORY_SEPARATOR, $relative );
			$real_path = realpath( $candidate );
			if ( false === $real_path || ! is_readable( $real_path ) ) {
				return null;
			}

			$prefix = rtrim( $real_root, '\\/' ) . DIRECTORY_SEPARATOR;
			if ( 0 !== strpos( $real_path, $prefix ) ) {
				return null;
			}

			return $real_path;
		}

		/** Safe log diagnostic: generic code only — no paths or user data. */
		private static function log_safe( string $code ): void {
			error_log( 'HAL Frontend Dashboard: template ' . $code . '.' ); // phpcs:ignore WordPress.PHP.DevelopmentFunctions.error_log_error_log -- Refined diagnostic for the administrator only (§8.1).
		}
	}

	// Registration at load: the MU Runtime loads early, and the filter is
	// evaluated at template_include time after all modules are complete —
	// no dependency on load order beyond this file.
	HAL_Frontend_Dashboard_Template_Controller::register();
}
